#define lcn40tab_upload(dev, offset, data) \
	b43_lcntab_write_bulk(dev, offset, ARRAY_SIZE(data), data)

void b43_phy_lcn40_tables_init(struct b43_wldev *dev)
{
	lcn40tab_upload(dev, B43_LCNTAB16(0x02, 0), b43_lcn40tab_0x02);
	lcn40tab_upload(dev, B43_LCNTAB16(0x01, 0), b43_lcntab_0x01);
	lcn40tab_upload(dev, B43_LCNTAB32(0x0d, 0), b43_lcn40tab_0x0d);
	lcn40tab_upload(dev, B43_LCNTAB16(0x0f, 0), b43_lcn40tab_0x0f);
	lcn40tab_upload(dev, B43_LCNTAB16(0x10, 0), b43_lcn40tab_0x10);
	lcn40tab_upload(dev, B43_LCNTAB16(0x11, 0), b43_lcn40tab_0x11);
	lcn40tab_upload(dev, B43_LCNTAB32(0x12, 0), b43_lcn40tab_0x12);
	lcn40tab_upload(dev, B43_LCNTAB16(0x14, 0), b43_lcn40tab_0x14);
	lcn40tab_upload(dev, B43_LCNTAB16(0x17, 0), b43_lcntab_0x17);
	lcn40tab_upload(dev, B43_LCNTAB16(0x00, 0), b43_lcntab_0x00);
	lcn40tab_upload(dev, B43_LCNTAB32(0x18, 0), b43_lcntab_0x18);

	/* Then 0x11, 0x12 and 0x0d again, with other contents */
	lcn40tab_upload(dev, B43_LCNTAB16(0x11, 0), b43_lcn40tab_0x11_b);
	lcn40tab_upload(dev, B43_LCNTAB32(0x12, 0), b43_lcn40tab_0x12_b);
	lcn40tab_upload(dev, B43_LCNTAB32(0x0d, 0), b43_lcn40tab_0x0d_b);
	lcn40tab_upload(dev, B43_LCNTAB32(0x0b, 0), b43_lcn40tab_0x0b);
}
